REF_RE = re.compile(r"(?<![\w./<-])((?:[\w.-]+/)*[\w.-]+\.(?:py|json|md|sh))\b")


def ref_exists(ref, base_dir=None):
    if "*" in ref or ref.startswith("http"):
        return True
    cands = [P(ref), os.path.join(SRC, ref)] + ([os.path.join(base_dir, ref)] if base_dir else [])
    if any(os.path.exists(c) for c in cands):
        return True
    base = os.path.basename(ref)
    if "/" not in ref:  # bare basename: accept a unique-enough match anywhere in the repo
        for dp, dn, fn in os.walk(ROOT):
            if base in fn:
                return True
    return False


def check_m():
    texts = []
    for rel in ("README.md", "CHANGELOG.md"):
        if os.path.isfile(P(rel)):
            texts.append((rel, open(P(rel), encoding="utf-8").read()))
    if os.path.isfile(P("registry.manifest.json")):
        texts.append(("registry.manifest.json", open(P("registry.manifest.json"), encoding="utf-8").read()))
    for fp in glob.glob(P("**/*.py"), recursive=True):
        try:
            d = ast.get_docstring(ast.parse(open(fp, encoding="utf-8").read()))
        except SyntaxError:
            d = None
        if d:
            texts.append((os.path.relpath(fp, ROOT), d))
    bad, warn, n = [], [], 0
    for src, t in texts:
        for m in REF_RE.finditer(t):
            ref = m.group(1)
            if ref.startswith("design-repo/"):
                ref = ref[len("design-repo/"):]
            n += 1
            if ref_exists(ref, os.path.dirname(P(src))):
                continue
            if not HAVE_SRC and (ref.startswith("src/") or ref in ("package.json", "CLONE_SPEC.md", "CLONE_ASSETS.md") or ref.endswith(".jsx")):
                continue
            if ref.startswith("schema/tests/") and not os.path.isdir(P("schema/tests")):
                warn.append(f"{src}: {ref}")
                continue
            if ref.startswith("src/") or ref.endswith((".jsx", ".js")):
                continue  # source-project evidence, not a package file
            bad.append(f"{src}: references missing file `{ref}`")
    for b in sorted(set(bad)):
        rec("FAIL", "m.referenced-files", b)
    for w in sorted(set(warn)):
        rec("WARN", "m.referenced-files", f"{w} (schema/tests missing)")
    if not bad:
        rec("PASS", "m.referenced-files", f"{n} file references in docstrings/README/CHANGELOG/manifest resolve")


