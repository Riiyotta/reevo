#!/usr/bin/env python3
"""One-shot verification of the whole design-repo. Exit 1 on any FAIL.

    python3 extraction/verify_all.py                    # run every check
    python3 extraction/verify_all.py --citation-selftest   # prove the citation resolver on a synthetic tree
    python3 extraction/verify_all.py --update-counts    # recompute manifest `counts` + README count block, then exit

Stdlib + jsonschema. The repo root is derived from this file's location; the source project
(external evidence) is the folder ABOVE the repo root. When that sibling tree is absent, checks that
need it degrade to WARN (they are never silently passed as PASS).

Companion scripts (all must exist; checked by check m):
  extraction/build_schema.py  extraction/prove_drift.py  schema/tests/adversarial_test.py
  templates/verify_routes.py  compatibility/verify_rules.py  schema/semantic_validate.py
"""
