def collect_roles():
    used = set()
    def walk(x):
        if isinstance(x, dict):
            for k, v in x.items():
                if k == "assetRole":
                    if isinstance(v, str):
                        used.add(v)
                    elif isinstance(v, dict) and isinstance(v.get("const"), str):
                        used.add(v["const"])
                walk(v)
        elif isinstance(x, list):
            [walk(v) for v in x]
    for pat in ("sections/*.json", "primitives/*.json", "components/*.json", "schema/pagespec.schema.json"):
        for fp in glob.glob(P(pat)):
            walk(json.load(open(fp, encoding="utf-8")))
    schema = jload("schema/pagespec.schema.json")
    for k in schema["definitions"]:
        if k.startswith("assetRef."):
            used.add(k.split(".", 1)[1])
    return used


