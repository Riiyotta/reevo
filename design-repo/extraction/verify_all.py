ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.dirname(ROOT)  # source project = sibling tree one level up
HAVE_SRC = os.path.isdir(os.path.join(SRC, "src"))

CITE_KEYS = {"measuredFrom", "usedAt", "usedBy"}
CITE_RE = re.compile(r"([A-Za-z0-9_./@\[\]-]+\.[A-Za-z0-9]+):(\d+)(?:-(\d+))?")
COUNTS_BEGIN = "<!-- counts:begin (generated by extraction/verify_all.py --update-counts) -->"
COUNTS_END = "<!-- counts:end -->"
POLICY_ENUM = ["may-generate-new", "must-reuse-exact", "must-not-fabricate", "must-not-reuse-live-endpoint"]

RESULTS = []  # (status, check, message)


def rec(status, check, msg=""):
    RESULTS.append((status, check, msg))
    print(f"{status:4} [{check}] {msg}".rstrip())


def P(rel):
    return os.path.join(ROOT, rel)


def jload(rel):
    with open(P(rel), encoding="utf-8") as f:
        return json.load(f)


def all_json_files():
    out = []
    for dp, dn, fn in os.walk(ROOT):
        dn[:] = [d for d in dn if d not in ("__pycache__", ".git", "node_modules")]
        out += [os.path.join(dp, f) for f in fn if f.endswith(".json")]
    return sorted(out)


def load_module(name, rel):
    spec = importlib.util.spec_from_file_location(name, P(rel))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def py_functions(rel):
    with open(P(rel), encoding="utf-8") as f:
        tree = ast.parse(f.read())
    return {n.name for n in ast.walk(tree) if isinstance(n, ast.FunctionDef)}


# ------------------------------------------------------------------ citations
_line_cache = {}


def line_count(path):
    if path not in _line_cache:
        try:
            with open(path, encoding="utf-8", errors="replace") as f:
                _line_cache[path] = len(f.read().splitlines())
        except OSError:
            _line_cache[path] = None
    return _line_cache[path]


def check_citation(src_root, path, a, b=None):
    """Return None if `path:a[-b]` resolves inside src_root, else a reason string."""
    n = line_count(os.path.join(src_root, path))
    if n is None:
        return f"file missing: {path}"
    b = a if b is None else b
    if a < 1 or b < a:
        return f"bad range {path}:{a}-{b}"
    if b > n:
        return f"range exceeds file: {path}:{a}-{b} (file has {n} lines)"
    return None


def collect_citations(root):
    """Yield (jsonfile, jsonpath, citation-string) for every string under measuredFrom/usedAt/usedBy."""
    found = []

    def walk(x, f, p, inkey):
        if isinstance(x, dict):
            for k, v in x.items():
                walk(v, f, f"{p}.{k}", inkey or k in CITE_KEYS)
        elif isinstance(x, list):
            for i, v in enumerate(x):
                walk(v, f, f"{p}[{i}]", inkey)
        elif isinstance(x, str) and inkey:
            found.append((f, p, x))

    for fp in all_json_files():
        try:
            with open(fp, encoding="utf-8") as fh:
                walk(json.load(fh), os.path.relpath(fp, root), "", False)
        except ValueError:
            pass
    return found


def citation_selftest():
    ok = True
    with tempfile.TemporaryDirectory() as td:
        os.makedirs(os.path.join(td, "src"))
        with open(os.path.join(td, "src", "a.js"), "w") as f:
            f.write("\n".join(f"line {i}" for i in range(1, 11)) + "\n")  # 10 lines
        cases = [
            (("src/a.js", 1, 10), False, "full file"),
            (("src/a.js", 5, None), False, "single line"),
            (("src/a.js", 1, 11), True, "past EOF"),
            (("src/a.js", 11, None), True, "single line past EOF"),
            (("src/missing.js", 1, 2), True, "missing file"),
            (("src/a.js", 7, 3), True, "reversed range"),
            (("src/a.js", 0, 3), True, "zero start"),
        ]
        for args, should_fail, label in cases:
            r = check_citation(td, *args)
            good = (r is not None) == should_fail
            ok &= good
            print(f"{'ok  ' if good else 'BAD '} selftest {label}: {r or 'resolved'}")
    print("CITATION SELFTEST", "PASS" if ok else "FAIL")
    return 0 if ok else 1


# ------------------------------------------------------------------ counts
def count_leaves(x):
    """Token leaf = dict holding `value` (or `ref` for theme tokens)."""
    if isinstance(x, dict):
        if "value" in x or "ref" in x:
            return 1
        return sum(count_leaves(v) for k, v in x.items() if not k.startswith("$"))
    return 0


def layer_count(layer):
    n = 0
    for fp in sorted(glob.glob(P(f"tokens/{layer}/*.json"))):
        d = json.load(open(fp, encoding="utf-8"))
        n += sum(count_leaves(v) for k, v in d.items() if isinstance(v, dict) and k not in ("$description",))
    return n


def compute_counts():
    themes = {}
    for fp in sorted(glob.glob(P("tokens/themes/*.json"))):
        d = json.load(open(fp, encoding="utf-8"))
        themes[d["theme"]] = count_leaves(d["tokens"])
    tok = {"foundation": layer_count("00-foundation"), "semantic": layer_count("10-semantic"),
           "component": layer_count("20-component"), "layout": layer_count("30-layout")}
    tok["total"] = sum(tok.values())
    tok["themeResolved"] = themes
    routes = jload("templates/routes.json")
    al = jload("tokens/llm/component-allowlist.json")["components"]
    return {
        "tokens": tok,
        "primitives": len(glob.glob(P("primitives/*.json"))),
        "components": len(glob.glob(P("components/*.json"))),
        "sections": len(glob.glob(P("sections/*.json"))),
        "templates": len(jload("templates/templates.json")["templates"]),
        "routes": len(routes["routes"]),
        "routePatterns": sum(1 for r in routes["routes"] if ":" in r["path"]),
        "concreteUrls": sum(r["concreteUrlCount"] for r in routes["routes"]),
        "rules": len(jload("compatibility/graph.json")["rules"]),
        "assetRoles": len(jload("assets/asset-roles.json")["roles"]),
        "allowlistEntries": len(al),
    }


def counts_block(c):
    t = c["tokens"]
    rows = [
        ("Design tokens (foundation / semantic / component / layout)",
         f"{t['total']} ({t['foundation']} / {t['semantic']} / {t['component']} / {t['layout']})"),
        ("Resolved theme tokens (light / dark)", f"{t['themeResolved'].get('light')} / {t['themeResolved'].get('dark')}"),
        ("Primitives", c["primitives"]), ("Components", c["components"]), ("Sections", c["sections"]),
        ("Allowlist entries", c["allowlistEntries"]), ("Templates", c["templates"]),
        ("Route entries (incl. `*` catch-all)", c["routes"]),
        ("Parameterised route patterns", c["routePatterns"]),
        ("Concrete URLs", c["concreteUrls"]), ("Graph rules", c["rules"]), ("Asset roles", c["assetRoles"]),
    ]
    out = [COUNTS_BEGIN, "", "| Item | Count |", "|---|---|"]
    out += [f"| {a} | {b} |" for a, b in rows]
    out += ["", COUNTS_END]
    return "\n".join(out)


def update_counts():
    c = compute_counts()
    m = jload("registry.manifest.json")
    m["counts"] = c
    with open(P("registry.manifest.json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(m, indent=2, ensure_ascii=False) + "\n")
    rp = P("README.md")
    txt = open(rp, encoding="utf-8").read()
    pat = re.compile(re.escape(COUNTS_BEGIN) + r".*?" + re.escape(COUNTS_END), re.S)
    if pat.search(txt):
        txt = pat.sub(lambda _m: counts_block(c), txt)
        with open(rp, "w", encoding="utf-8", newline="\n") as f:
            f.write(txt)
    print("updated manifest counts and README block")
    return 0


