    for b in bad[:60]:
        rec("FAIL", "e.citations", b)
    if len(bad) > 60:
        rec("FAIL", "e.citations", f"... {len(bad) - 60} more")
    if not bad:
        rec("PASS", "e.citations", f"{n} citations in {len(cites)} fields all resolve against the source tree")


